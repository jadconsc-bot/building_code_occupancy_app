/**
 * Certification Signature Service
 * 
 * Generates and verifies digital signatures for compliance certificates
 * Ensures code integrity and legal defensibility through cryptographic signatures
 * 
 * ⚠️ LEGAL LAYER INTACT
 * All signatures include certificate chain and public key verification
 * 
 * Backwards Compatible: Supports multiple signature algorithms
 * Code Integrity: Immutable signature generation with audit trail
 * Revision Control: Version tracking for algorithm changes
 */

import crypto from 'crypto';
import { logger } from './logger';
import { DigitalSignatureSchema, ComplianceCertificateSchema } from './certificationFormat.schema';

/**
 * Signature Algorithm Configuration
 * Defines supported algorithms and their parameters
 */
export const SIGNATURE_ALGORITHMS = {
  'RSA-SHA256': {
    algorithm: 'RSA-SHA256',
    keySize: 2048,
    hashAlgorithm: 'sha256',
    padding: crypto.constants.RSA_PKCS1_PSS_PADDING,
  },
  'ECDSA-SHA256': {
    algorithm: 'ECDSA-SHA256',
    keySize: 256,
    hashAlgorithm: 'sha256',
    curve: 'prime256v1',
  },
} as const;

/**
 * Certificate Signature Service
 * Handles digital signature generation and verification
 */
export class CertificateSignatureService {
  private privateKey: crypto.KeyObject | null = null;
  private publicKey: crypto.KeyObject | null = null;
  private algorithm: keyof typeof SIGNATURE_ALGORITHMS = 'RSA-SHA256';
  private certificateChain: string[] = [];

  /**
   * Initialize the signature service with keys
   * @param privateKeyPem - Private key in PEM format
   * @param publicKeyPem - Public key in PEM format
   * @param certificateChainPem - Certificate chain in PEM format
   * @param algorithm - Signature algorithm to use
   */
  constructor(
    privateKeyPem: string,
    publicKeyPem: string,
    certificateChainPem: string[],
    algorithm: keyof typeof SIGNATURE_ALGORITHMS = 'RSA-SHA256'
  ) {
    try {
      this.privateKey = crypto.createPrivateKey(privateKeyPem);
      this.publicKey = crypto.createPublicKey(publicKeyPem);
      this.certificateChain = certificateChainPem;
      this.algorithm = algorithm;

      logger.info('CertificateSignatureService initialized', {
        algorithm,
        keyType: this.privateKey.type,
        certificateChainLength: certificateChainPem.length,
      });
    } catch (error) {
      logger.error('Failed to initialize CertificateSignatureService', { error });
      throw error;
    }
  }

  /**
   * Generate a digital signature for certificate data
   * @param certificateData - The certificate data to sign
   * @param userId - User ID of the signer
   * @param userName - Name of the signer
   * @param userEmail - Email of the signer
   * @param userRole - Role of the signer
   * @returns Digital signature object
   */
  async generateSignature(
    certificateData: string,
    userId: number,
    userName: string,
    userEmail: string,
    userRole: 'user' | 'admin' | 'professional_reviewer'
  ): Promise<z.infer<typeof DigitalSignatureSchema>> {
    try {
      if (!this.privateKey) {
        throw new Error('Private key not initialized');
      }

      // Create hash of certificate data
      const hash = crypto.createHash(SIGNATURE_ALGORITHMS[this.algorithm].hashAlgorithm);
      hash.update(certificateData);
      const dataHash = hash.digest();

      // Generate signature
      let signatureValue: Buffer;

      if (this.algorithm === 'RSA-SHA256') {
        signatureValue = crypto.sign(
          SIGNATURE_ALGORITHMS[this.algorithm].hashAlgorithm,
          dataHash,
          {
            key: this.privateKey,
            padding: SIGNATURE_ALGORITHMS[this.algorithm].padding,
          }
        );
      } else if (this.algorithm === 'ECDSA-SHA256') {
        signatureValue = crypto.sign(
          SIGNATURE_ALGORITHMS[this.algorithm].hashAlgorithm,
          dataHash,
          this.privateKey
        );
      } else {
        throw new Error(`Unsupported algorithm: ${this.algorithm}`);
      }

      // Calculate public key hash for verification
      const publicKeyHash = crypto
        .createHash('sha256')
        .update(this.publicKey!.export({ format: 'pem', type: 'spki' }))
        .digest('hex');

      const signature = {
        algorithm: this.algorithm,
        signatureValue: signatureValue.toString('base64'),
        certificateChain: this.certificateChain.map(cert => cert.toString('base64')),
        signedAt: new Date(),
        signedBy: {
          userId,
          userName,
          userEmail,
          userRole,
        },
        publicKeyHash,
      };

      logger.info('Digital signature generated', {
        algorithm: this.algorithm,
        userId,
        signatureLength: signatureValue.length,
        publicKeyHash,
      });

      return signature;
    } catch (error) {
      logger.error('Failed to generate digital signature', { error });
      throw error;
    }
  }

  /**
   * Verify a digital signature
   * @param certificateData - The original certificate data
   * @param signature - The digital signature to verify
   * @returns True if signature is valid, false otherwise
   */
  async verifySignature(
    certificateData: string,
    signature: z.infer<typeof DigitalSignatureSchema>
  ): Promise<boolean> {
    try {
      if (!this.publicKey) {
        throw new Error('Public key not initialized');
      }

      // Recreate hash of certificate data
      const hash = crypto.createHash(SIGNATURE_ALGORITHMS[signature.algorithm].hashAlgorithm);
      hash.update(certificateData);
      const dataHash = hash.digest();

      // Decode signature from base64
      const signatureBuffer = Buffer.from(signature.signatureValue, 'base64');

      // Verify signature
      let isValid: boolean;

      if (signature.algorithm === 'RSA-SHA256') {
        isValid = crypto.verify(
          SIGNATURE_ALGORITHMS[signature.algorithm].hashAlgorithm,
          dataHash,
          {
            key: this.publicKey,
            padding: SIGNATURE_ALGORITHMS[signature.algorithm].padding,
          },
          signatureBuffer
        );
      } else if (signature.algorithm === 'ECDSA-SHA256') {
        isValid = crypto.verify(
          SIGNATURE_ALGORITHMS[signature.algorithm].hashAlgorithm,
          dataHash,
          this.publicKey,
          signatureBuffer
        );
      } else {
        throw new Error(`Unsupported algorithm: ${signature.algorithm}`);
      }

      // Verify public key hash matches
      const currentPublicKeyHash = crypto
        .createHash('sha256')
        .update(this.publicKey.export({ format: 'pem', type: 'spki' }))
        .digest('hex');

      const publicKeyHashMatch = currentPublicKeyHash === signature.publicKeyHash;

      logger.info('Digital signature verification', {
        algorithm: signature.algorithm,
        isValid,
        publicKeyHashMatch,
        userId: signature.signedBy.userId,
      });

      return isValid && publicKeyHashMatch;
    } catch (error) {
      logger.error('Failed to verify digital signature', { error });
      return false;
    }
  }

  /**
   * Generate a certificate chain hash for audit trail
   * @returns SHA-256 hash of certificate chain
   */
  generateCertificateChainHash(): string {
    const hash = crypto.createHash('sha256');
    for (const cert of this.certificateChain) {
      hash.update(cert);
    }
    return hash.digest('hex');
  }

  /**
   * Get the public key in PEM format
   * @returns Public key in PEM format
   */
  getPublicKeyPem(): string {
    if (!this.publicKey) {
      throw new Error('Public key not initialized');
    }
    return this.publicKey.export({ format: 'pem', type: 'spki' }).toString();
  }

  /**
   * Get signature algorithm info
   * @returns Algorithm configuration
   */
  getAlgorithmInfo() {
    return {
      algorithm: this.algorithm,
      ...SIGNATURE_ALGORITHMS[this.algorithm],
      certificateChainLength: this.certificateChain.length,
      certificateChainHash: this.generateCertificateChainHash(),
    };
  }
}

/**
 * Generate RSA key pair for testing/development
 * ⚠️ FOR DEVELOPMENT ONLY - Use proper key management in production
 */
export function generateRSAKeyPair(): {
  publicKey: string;
  privateKey: string;
} {
  const { publicKey, privateKey } = crypto.generateKeyPairSync('rsa', {
    modulusLength: 2048,
    publicKeyEncoding: {
      type: 'spki',
      format: 'pem',
    },
    privateKeyEncoding: {
      type: 'pkcs8',
      format: 'pem',
    },
  });

  return {
    publicKey: publicKey as string,
    privateKey: privateKey as string,
  };
}

/**
 * Generate ECDSA key pair for testing/development
 * ⚠️ FOR DEVELOPMENT ONLY - Use proper key management in production
 */
export function generateECDSAKeyPair(): {
  publicKey: string;
  privateKey: string;
} {
  const { publicKey, privateKey } = crypto.generateKeyPairSync('ec', {
    namedCurve: 'prime256v1',
    publicKeyEncoding: {
      type: 'spki',
      format: 'pem',
    },
    privateKeyEncoding: {
      type: 'pkcs8',
      format: 'pem',
    },
  });

  return {
    publicKey: publicKey as string,
    privateKey: privateKey as string,
  };
}

